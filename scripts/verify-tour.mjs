import assert from 'node:assert/strict';
import { mkdtemp, readFile, readdir, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawn } from 'node:child_process';
import { chromium } from 'playwright';
import { apps, owner } from '../src/data.js';
import { instructions, parseTour } from '../tools/tours/lexicon.js';
import { playTour } from '../tools/tours/playback.js';

const base = process.env.TEST_URL || 'http://127.0.0.1:5173/';
const output = await mkdtemp(join(tmpdir(), 'portfolio-tour-check-'));
const browser = await chromium.launch({ channel: 'chromium' });
const errors = [];
try {
  const editor = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  editor.on('pageerror', error => errors.push(error.message));
  await editor.goto(new URL('/tour-builder.html', base).href);
  assert.equal(await editor.locator('.instruction').count(), instructions.length);
  const rows = editor.locator('.sequence li');
  assert.equal(await rows.count(), 8);
  const paletteWait = editor.locator('.instruction').filter({ has: editor.getByRole('heading', { name: 'Wait N seconds', exact: true }) });
  await paletteWait.dragTo(editor.locator('.drop-zone'));
  await rows.nth(8).waitFor({ timeout: 3000 });
  assert.equal(await rows.count(), 9);
  await rows.last().locator('input').fill('1.25');
  const grip = rows.last().locator('.handle');
  await grip.scrollIntoViewIfNeeded();
  const start = await grip.boundingBox();
  await editor.mouse.move(start.x + start.width / 2, start.y + start.height / 2);
  await editor.mouse.down();
  await editor.mouse.move(start.x + start.width / 2 + 16, start.y + start.height / 2, { steps: 4 });
  await rows.nth(1).scrollIntoViewIfNeeded();
  const target = await rows.nth(1).boundingBox();
  await editor.mouse.move(target.x + target.width / 2, target.y + target.height / 2, { steps: 5 });
  await editor.mouse.move(target.x + target.width / 2, target.y + target.height / 2 + 1);
  await editor.mouse.up();
  assert.equal(await rows.nth(1).locator('input').inputValue(), '1.25');
  await editor.getByRole('button', { name: 'Remove step 2', exact: true }).click();
  await editor.getByRole('button', { name: 'Move step 3 down', exact: true }).click();
  assert.ok((await rows.nth(2).innerText()).includes('Swipe right'));
  await editor.getByRole('button', { name: 'Move step 4 up', exact: true }).click();
  await editor.getByRole('button', { name: 'Add Open project', exact: true }).click();
  await rows.last().getByRole('combobox').selectOption(apps[0].name);
  assert.ok((await editor.getByLabel('Script preview').innerText()).includes(`Open project ${JSON.stringify(apps[0].name)}`));
  await editor.getByRole('button', { name: 'Remove step 9', exact: true }).click();
  const wait = rows.nth(1).locator('input');
  await wait.fill('0');
  assert.ok(await editor.getByRole('button', { name: 'Download tour.txt ↓' }).isDisabled());
  await wait.fill('0.1');
  const downloaded = editor.waitForEvent('download');
  await editor.getByRole('button', { name: 'Download tour.txt ↓' }).click();
  const download = await downloaded;
  assert.equal(download.suggestedFilename(), 'tour.txt');
  const text = await readFile(await download.path(), 'utf8');
  assert.equal(text.trim(), (await editor.getByLabel('Script preview').innerText()).trim());
  assert.equal(parseTour(text).length, 8);
  await editor.locator('.palette, .sequence').evaluateAll(panels => panels.forEach(panel => { panel.scrollTop = 0; }));
  await editor.screenshot({ path: join(output, 'builder-desktop.png'), fullPage: true });
  await editor.setViewportSize({ width: 390, height: 844 });
  assert.ok(await editor.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await editor.screenshot({ path: join(output, 'builder-mobile.png') });
  await editor.getByRole('button', { name: 'Remove step 1', exact: true }).click();
  assert.ok(await editor.getByRole('button', { name: 'Download tour.txt ↓' }).isDisabled());
  while (await rows.count()) await editor.getByRole('button', { name: 'Remove step 1', exact: true }).click();
  assert.ok(await editor.getByRole('button', { name: 'Download tour.txt ↓' }).isDisabled());

  const context = await browser.newContext({ viewport: { width: 440, height: 956 }, recordVideo: { dir: output, size: { width: 440, height: 956 } } });
  const page = await context.newPage();
  page.setDefaultTimeout(4000);
  page.on('pageerror', error => errors.push(error.message));
  const exported = text.replace('Wait 3 seconds', 'Wait 0.1 seconds');
  await playTour(page, parseTour(exported), base);
  assert.equal(await page.locator('#view-profile').isVisible(), true);
  await assert.rejects(playTour(page, parseTour('Open app\nOpen Chats\nOpen first conversation'), base), /Line 3/);
  const externalProject = apps.find(app => app.githubUrl && app.websiteUrl);
  const extra = `Open app\nOpen Browser\nScroll down\nScroll up\nOpen project ${JSON.stringify(externalProject.name)}\nClick Share\nClick Superlike\nClick Undo\nClick Pass\nOpen project ${JSON.stringify(externalProject.name)}\nClick Like\nOpen Chats\nOpen conversation ${JSON.stringify(externalProject.name)}\nClick link to author\nGo back\nOpen Profile\n`;
  const contacts = owner.links.map(link => `Click contact ${JSON.stringify(link.label)}`).join('\n');
  await playTour(page, parseTour(extra + contacts + (owner.email ? '\nClick email' : '')), base);
  assert.equal(context.pages().length, 1);
  const video = page.video();
  await context.close();
  const bytes = await readFile(await video.path());
  assert.deepEqual([...bytes.subarray(0, 4)], [0x1a, 0x45, 0xdf, 0xa3]);
  assert.ok(bytes.length > 10000);

  const runCli = file => new Promise((resolve, reject) => {
    const child = spawn(process.execPath, ['scripts/demo.mjs', file, '--url', base]);
    let log = '';
    child.stdout.on('data', data => log += data); child.stderr.on('data', data => log += data);
    child.on('error', reject); child.on('exit', code => resolve({ code, log }));
  });
  const failure = join(output, 'failure.txt');
  await writeFile(failure, 'Open app\nClick Undo\n');
  const result = await runCli(failure);
  assert.equal(result.code, 1);
  assert.match(result.log, /Line 2/);
  assert.match(result.log, /Recording \(partial\):/);
  const bad = join(output, 'invalid.txt');
  await writeFile(bad, 'Open app\nFly away');
  const invalid = await runCli(bad);
  assert.equal(invalid.code, 1);
  assert.match(invalid.log, /Line 2/);
  assert.doesNotMatch(invalid.log, /Recording/);
  assert.deepEqual(errors, []);
  const dist = await readdir(new URL('../dist/', import.meta.url));
  assert.ok(!dist.includes('tour-builder.html'));
  console.log(`Passed: builder drag/drop, reorder buttons, inputs, text download, mobile layout, tour playback, external destinations, history, unavailable actions, CLI partial video, and production exclusion. QA files: ${output}`);
} finally { await browser.close(); }
